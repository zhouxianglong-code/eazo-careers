export function filterJobs(query: string, department: string, type: string) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  return jobs.filter(
    (job) =>
      (department === '全部团队' || job.department === department) &&
      (type === '全部类型' || job.type === type) &&
      terms.every((term) =>
        `${job.title} ${job.english} ${job.location} ${job.tags.join(' ')} ${job.summary}`
          .toLocaleLowerCase()
          .includes(term),
      ),
  )
}
export function applicationUrl(job: Job, recipient = company.email) {
  if (!recipient) return null
  const body = `你好，我希望申请 Eazo 的${job.title}。\n\n姓名：\n联系方式：\n\n申请材料：\n${job.application}\n\n请在发送前检查附件及链接。`
  return `mailto:${recipient}?subject=${encodeURIComponent(`Eazo 职位申请｜${job.title}`)}&body=${encodeURIComponent(body)}`
}
